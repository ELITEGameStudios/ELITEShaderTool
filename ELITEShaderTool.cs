	// Please read https://github.com/tModLoader/tModLoader/wiki/Basic-tModLoader-Modding-Guide#mod-skeleton-contents for more information about the various files in a mod.
	public class ELITEShaderTool : Mod
	{
		// Process window;

		Process window;
		public bool hasStarted;
        public override void Load()
        {
			return;
			
			try
			{
				window = new Process();
				window.StartInfo.FileName = window.StartInfo.FileName = GetModDirectory()+@"\PhotinoBuild\HelloPhotino.NET.exe";
				// Path.Combine(GetModDirectory(), "PhotinoBuild", "HelloPhotino.NET.exe");

				window.StartInfo.WorkingDirectory = Path.GetDirectoryName(window.StartInfo.FileName)!;

				window.StartInfo.UseShellExecute = false;

				// Debugging code below is generated by AI, meant to help logging and debugging if photino doesnt work
				window.StartInfo.RedirectStandardOutput = true;
				window.StartInfo.RedirectStandardError = true;
				window.EnableRaisingEvents = true;
				window.Start();
				window.BeginOutputReadLine();
				window.BeginErrorReadLine();
				window.OutputDataReceived += (_, e) =>
				{
					if (e.Data != null)
						Logger.Info($"Photino OUT: {e.Data}");
				};

				window.ErrorDataReceived += (_, e) =>
				{
					if (e.Data != null)
						Logger.Error($"Photino ERR: {e.Data}");
				};
				Logger.Info($"Photino started: {hasStarted}");
				Logger.Info($"PID: {window.Id}");
				Logger.Info($"Path: {window.StartInfo.FileName}");
				Logger.Info($"Working directory: {window.StartInfo.WorkingDirectory}");

				// window = new Process();
				// window.StartInfo.UseShellExecute = false;
				// hasStarted = window.Start();
				// window.StartInfo.CreateNoWindow = false;
				// window.StartInfo.WindowStyle = ProcessWindowStyle.Maximized;
				// window.PriorityClass = ProcessPriorityClass.High;


				// FXC argument sample:
				//fxc /Zi /Gec /T ps_3_0 /Fo RocketRamEffect.fxc RocketRamEffect.fx
				// /Zi for debugging, /Gec for DX9 compatibility, /T has to match shader model, /Fo to output fxc object file, output file, input file
			}
			catch(Exception e)
			{
				Console.WriteLine(e.Message);
			}
        }
        public override void Unload()
        {
			try
			{
				window?.Close();
			}
			catch(Exception e)
			{
				Console.WriteLine(e.Message);
			}
        }

		public string GetModDirectory()
		{
			return ModDirectory();
		}

        private string ModDirectory([CallerFilePath] string thisPath = "")
        {
            return Path.GetDirectoryName(thisPath);
        }
		
